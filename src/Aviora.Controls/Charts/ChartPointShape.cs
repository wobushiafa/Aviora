namespace Aviora.Controls;

/// <summary>
/// Specifies the marker shape drawn for data points on a <see cref="LineChart"/>.
/// </summary>
public enum ChartPointShape
{
    /// <summary>Circular point marker.</summary>
    Circle,

    /// <summary>Square point marker.</summary>
    Square,

    /// <summary>Diamond (45-degree rotated square) point marker.</summary>
    Diamond,

    /// <summary>Upward-pointing triangular marker.</summary>
    Triangle,
}
