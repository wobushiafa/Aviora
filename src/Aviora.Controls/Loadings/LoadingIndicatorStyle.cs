namespace Aviora.Controls;

/// <summary>
/// Specifies the built-in visual used by a <see cref="Loading"/> control.
/// </summary>
public enum LoadingIndicatorStyle
{
    /// <summary>A rotating arc.</summary>
    Ring,

    /// <summary>Three animated dots.</summary>
    Dots,

    /// <summary>Expanding concentric circles.</summary>
    Pulse,

    /// <summary>Animated vertical bars.</summary>
    Bars,

    /// <summary>Five dots moving in a wave.</summary>
    Wave,

    /// <summary>Dots orbiting around a center point.</summary>
    Orbit,

    /// <summary>Two counter-rotating arcs.</summary>
    DoubleRing,
}
