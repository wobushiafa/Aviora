namespace Aviora.Presentation.Toasts;

/// <summary>Specifies where a toast is presented within its host.</summary>
public enum ToastPlacement
{
    /// <summary>The top-left corner.</summary>
    TopLeft,

    /// <summary>The top edge, horizontally centered.</summary>
    TopCenter,

    /// <summary>The top-right corner.</summary>
    TopRight,

    /// <summary>The bottom-left corner.</summary>
    BottomLeft,

    /// <summary>The bottom edge, horizontally centered.</summary>
    BottomCenter,

    /// <summary>The bottom-right corner.</summary>
    BottomRight,
}
